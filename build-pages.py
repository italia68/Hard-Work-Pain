#!/usr/bin/env python3
"""
build-pages.py — Hard Work & Pain static page generator (About / Contact / Updates)

WHAT THIS DOES
Generates three real, standalone, crawlable pages that sit alongside your
blog posts and Platemate page, following the exact same pattern as
build-blog.py:
  1. about/index.html
  2. contact/index.html   (includes a real working contact form via
                            FormSubmit.co — no backend needed)
  3. updates/index.html   (the changelog / "what's new" timeline)

These are separate from the main index.html single-page app. The SPA's
in-page About/Contact/Updates tabs keep working exactly as before for
anyone already on the site — this script just gives each of those sections
a real, independent, indexable URL for search engines and direct links.

HOW TO UPDATE CONTENT
The content for each page lives in the PAGES dict below, as plain HTML
strings (same style as a blog post body — <p>, <h2>, <ul>, etc.). Edit it
there, then run:  python3 build-pages.py

To add a new entry to the Updates timeline, add a new item to the
UPDATES_TIMELINE list (newest entry goes first) and re-run this script.

Sitemap note: sitemap.xml is now generated by build-blog.py (it already
includes /about/, /contact/, and /updates/ alongside your blog posts and
the Platemate page) — this script does NOT touch sitemap.xml, so there's
only one script that owns it and nothing gets silently dropped.

REQUIREMENTS
  Just Python 3, no packages to install. Run from the repo root (the same
  folder that contains index.html and build-blog.py).
"""

