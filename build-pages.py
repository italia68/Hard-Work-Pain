def json_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def build_pages():
    written = []
    for key, page in PAGES.items():
        canonical = f"{SITE_URL}/{page['path']}/"
        html = PAGE_TEMPLATE.format(
            title=page["title"],
            description=page["description"],
            description_json=json_escape(page["description"]),
            canonical=canonical,
            site_url=SITE_URL,
            schema_type=page["schema_type"],
            body=page["body"],
            extra_script=page["extra_script"],
            year=date.today().year,
        )
        out_dir = os.path.join(REPO_ROOT, page["path"])
        os.makedirs(out_dir, exist_ok=True)
        out_path = os.path.join(out_dir, "index.html")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(html)
        written.append((page["title"], canonical, out_path))
    return written


def main():
    written = build_pages()
    print(f"Built {len(written)} page(s):")
    for title, url, path in written:
        print(f"  - {title}  ->  {url}")
    print()
    print("Files written (commit/push, or paste into GitHub's web editor):")
    for _, _, path in written:
        print(f"  - {os.path.relpath(path, REPO_ROOT)}")
    print()
    print("Note: sitemap.xml already includes these URLs via build-blog.py —")
    print("no need to touch it here. Re-run build-blog.py if you want to")
    print("refresh the sitemap's lastmod dates.")


if __name__ == "__main__":
    main()
